// Parses the official roster workbook -> clean Grade 5–12 student data (IDs only, no names).
// Usage: node scripts/build-roster.js [path/to/roster.xlsx]
// Outputs: data/students.json, data/sections.json, data/students.csv, data/seed_students.sql, public/data/*.json
const fs = require('fs');
const path = require('path');
const { parseRosterWorkbook } = require('../public/js/shared/roster-parser.js');

const SRC = process.argv[2] || path.join(__dirname, '..', 'data', 'roster.xlsx');
const OUT = path.join(__dirname, '..', 'data');
const PUB = path.join(__dirname, '..', 'public', 'data');
const sq = s => String(s).replace(/'/g, "''");

(async () => {
  const { students, sections, notes } = await parseRosterWorkbook(fs.readFileSync(SRC));
  fs.mkdirSync(PUB, { recursive: true });
  for (const dir of [OUT, PUB]) {
    fs.writeFileSync(path.join(dir, 'students.json'), JSON.stringify(students, null, 1));
    fs.writeFileSync(path.join(dir, 'sections.json'), JSON.stringify(sections, null, 1));
  }
  // file:// friendly copy for DEMO mode (browsers block fetch() from file://). Delete in production.
  fs.writeFileSync(path.join(PUB, 'students-data.js'), '// DEMO ONLY — generated by scripts/build-roster.js. Delete in production (exposes Student IDs).\nwindow.STUDENTS_DATA = ' + JSON.stringify(students) + ';\n');
  const csv = ['student_id,grade_num,grade_label_en,grade_label_ar,track,section', ...students.map(s => [s.student_id, s.grade_num, s.grade_label_en, s.grade_label_ar, s.track, s.section].join(','))].join('\n');
  fs.writeFileSync(path.join(OUT, 'students.csv'), '﻿' + csv);
  const sql = ['-- Generated by scripts/build-roster.js — 30 sections, Grades 5–12', 'BEGIN;', ...students.map(s => `INSERT OR REPLACE INTO students (student_id,grade_num,grade_label_en,grade_label_ar,track,section) VALUES ('${sq(s.student_id)}',${s.grade_num},'${sq(s.grade_label_en)}','${sq(s.grade_label_ar)}','${s.track}','${sq(s.section)}');`), 'COMMIT;'].join('\n');
  fs.writeFileSync(path.join(OUT, 'seed_students.sql'), sql);
  const alnum = students.filter(s => /[A-Z]/.test(s.student_id)).map(s => s.student_id);
  console.log(`Sections: ${sections.length} | Students: ${students.length} | Alphanumeric: ${alnum.length} (${alnum.join(', ')})`);
  console.log(`Advanced: ${sections.filter(s => s.track === 'Advanced').map(s => s.section).join(', ')}`);
  if (notes.length) console.log('Notes:\n  ' + notes.join('\n  '));
})().catch(e => { console.error(e); process.exit(1); });
