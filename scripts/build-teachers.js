// Teacher list (متابعة رصد الاختبار التشخيصي 2026-2027.xlsx) -> teacher/subject/class assignments for Grades 5–12.
// Usage: node scripts/build-teachers.js [path/to/workbook.xlsx]
// Outputs: data/teachers.json, public/js/shared/teachers-data.js (window.TEACHERS_DATA / module.exports)
const ExcelJS = require('exceljs'); const fs = require('fs'); const path = require('path');
const SRC = process.argv[2] || path.join(__dirname, '..', 'data', 'teachers-source.xlsx');
const SUBJECT = { 'اللغة العربية': 'Arabic', 'التربية الإسلامية': 'Islamic Education', 'اللغة الإنجليزية': 'English', 'الرياضيات': 'Mathematics',
  'العلوم': 'Science', 'الدراسات الاجتماعية': 'Social Studies', 'الفيزياء': 'Physics', 'الكيمياء': 'Chemistry', 'الأحياء': 'Biology' };
const GRADE_WORD = { 5: 'خامس', 6: 'سادس', 7: 'سابع', 8: 'ثامن', 9: 'تاسع', 10: 'عاشر', 11: 'الحادي عشر', 12: 'الثاني عشر' };
// class code ("5/1", "9G1", "10A2") -> roster section name ("خامس 1", "تاسع عام 1", "عاشر متقدم 2")
const sectionsRoster = require(path.join(__dirname, '..', 'data', 'sections.json')).map(s => s.section);
function toSection(code) {
  let m = code.match(/^(\d+)\/(\d+)$/); if (m) return { grade: +m[1], track: 'General', section: `${GRADE_WORD[m[1]]} ${m[2]}` };
  m = code.match(/^(\d+)([GA])(\d+)$/); if (!m) return null;
  const grade = +m[1], track = m[2] === 'A' ? 'Advanced' : 'General';
  let section = `${GRADE_WORD[grade]} ${track === 'Advanced' ? 'متقدم' : 'عام'} ${m[3]}`;
  // the roster has a single Grade 11 Advanced section ("الحادي عشر متقدم 1") while the teacher sheet calls it 11A2
  if (!sectionsRoster.includes(section)) { const alt = sectionsRoster.filter(s => s.startsWith(`${GRADE_WORD[grade]} ${track === 'Advanced' ? 'متقدم' : 'عام'}`)); if (alt.length === 1) section = alt[0]; }
  return { grade, track, section };
}
(async () => {
  const wb = new ExcelJS.Workbook(); await wb.xlsx.readFile(SRC);
  const ws = wb.worksheets[0]; const rows = [], problems = [];
  ws.eachRow((r, i) => {
    if (i < 5) return; const v = r.values; const cycle = String(v[2] || ''), subAr = String(v[3] || '').trim(), name = String(v[4] || '').trim(), code = String(v[5] || '').trim();
    if (!subAr || !name || cycle === 'الأولى') return;
    const s = toSection(code), subject = SUBJECT[subAr];
    if (!s || !subject) { problems.push(`row ${i}: ${subAr} / ${code}`); return; }
    if (!sectionsRoster.includes(s.section)) problems.push(`row ${i}: section "${s.section}" (from ${code}) is not in the roster`);
    rows.push({ teacher: name, subject, subject_ar: subAr, class_code: code, grade_num: s.grade, track: s.track, section: s.section });
  });
  const teachers = [...new Set(rows.map(r => r.teacher))].sort((a, b) => a.localeCompare(b, 'ar')).map(n => ({ name: n, subjects: [...new Set(rows.filter(r => r.teacher === n).map(r => r.subject))] }));
  const data = { source: path.basename(SRC), generated: new Date().toISOString().slice(0, 10), teachers, assignments: rows };
  fs.writeFileSync(path.join(__dirname, '..', 'data', 'teachers.json'), JSON.stringify(data, null, 1));
  fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'shared', 'teachers-data.js'),
    `// GENERATED by scripts/build-teachers.js from ${data.source} — do not edit by hand.\n(function (root) { const D = ${JSON.stringify(data)};\n  if (typeof module === 'object' && module.exports) module.exports = D; else root.TEACHERS_DATA = D; })(typeof self !== 'undefined' ? self : this);\n`);
  console.log(`Teachers: ${teachers.length} | assignments: ${rows.length} | sections covered: ${new Set(rows.map(r => r.section)).size}/30`);
  if (problems.length) console.log('Problems:\n  ' + problems.join('\n  '));
})().catch(e => { console.error(e); process.exit(1); });
